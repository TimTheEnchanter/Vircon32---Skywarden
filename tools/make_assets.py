RATE = 44100
random.seed(11)

def write_sound(name, samples):
    pcm = [int(max(-1.0, min(1.0, s)) * 26000) for s in samples]
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(RATE)
        w.writeframes(b"".join(struct.pack("<hh", p, p) for p in pcm))
    with open(os.path.join(OUT, name + ".vsnd"), "wb") as f:   # for local testing only
        f.write(b"V32-VSND"); f.write(struct.pack("<I", len(pcm)))
        f.write(b"".join(struct.pack("<hh", p, p) for p in pcm))

def sq(ph): return 1.0 if (ph % 1.0) < 0.5 else -1.0
def tri(ph): return 4 * abs((ph % 1.0) - 0.5) - 1

def tone(dur, f0, f1, vol=0.4, fn=sq, release=0.4, vib=0.0):
    n = int(dur * RATE); out = []; ph = 0.0
    for i in range(n):
        t = i / n
        f = f0 + (f1 - f0) * t
        if vib: f *= 1 + vib * math.sin(2 * math.pi * 30 * i / RATE)
        ph += f / RATE
        e = min(1.0, i / 200.0) * min(1.0, (1 - t) / release if release > 0 else 1.0)
        out.append(vol * fn(ph) * e)
    return out

def noise(dur, vol=0.5, hold=4, grow=6, release=0.9):
    n = int(dur * RATE); out = []; v = 0.0
    for i in range(n):
        t = i / n
        h = max(1, int(hold * (1 + grow * t)))
        if i % h == 0: v = random.uniform(-1, 1)
        out.append(vol * v * min(1.0, (1 - t) / release))
    return out

def mix(a, b):
    n = max(len(a), len(b)); a = a + [0]*(n-len(a)); b = b + [0]*(n-len(b))
    return [x + y for x, y in zip(a, b)]

